package br.com.seridoplast.mlogbridge;

public final class TimedClickGateTest {
    private static int assertions;
    private static void check(boolean ok,String message){assertions++;if(!ok)throw new AssertionError(message);}
    public static void main(String[] args){
        check(TimedClickGate.COOLDOWN_MS==100L,"cooldown must be exactly 100ms");
        TimedClickGate gate = new TimedClickGate();
        check(gate.admitTrigger(1000),"first physical trigger should pass");
        check(gate.reserveClick(1001),"first native click should pass");
        check(!gate.reserveClick(1002),"same-cycle second click must be blocked");
        check(gate.admitBroadcast(1020),"first hardware broadcast admitted");
        check(!gate.admitBroadcast(1040),"echo of first hardware scan suppressed");
        check(!gate.admitTrigger(1080),"second physical trigger inside cooldown blocked");
        check(!gate.admitBroadcast(1090),"broadcast of blocked trigger suppressed");
        check(!gate.reserveClick(1090),"no click within cooldown");
        check(gate.remainingMs(1090)==10,"10ms remain");
        check(gate.remainingMs(1099)==1,"locked through t+99");
        check(gate.admitTrigger(1150),"unlocked after t+100 and debounce");
        check(gate.reserveClick(1151),"new click allowed once after cooldown");
        check(gate.admitBroadcast(1210),"second accepted cycle receives barcode");
        check(!gate.admitBroadcast(1230),"second duplicate blocked");
        check(gate.admitTrigger(2300),"third cycle should pass without Enter event");
        check(gate.reserveClick(2301),"third click allowed");
        check(!gate.admitTrigger(2350),"cooldown remains effective");
        check(gate.admitTrigger(2400),"automatic rearm without external event");
        TimedClickGate bounce = new TimedClickGate();
        check(bounce.admitTrigger(5000),"bounce baseline");
        check(!bounce.admitTrigger(5030),"bounce ignored");
        check(bounce.admitBroadcast(5080),"valid original broadcast still admitted");
        TimedClickGate broadcast = new TimedClickGate();
        check(broadcast.admitBroadcast(9000),"broadcast-only admission");
        check(broadcast.reserveClick(9002),"broadcast-only clicks once");
        check(!broadcast.admitBroadcast(9090),"broadcast-only cooldown enforced");
        check(broadcast.admitBroadcast(9100),"broadcast-only auto unlock");
        check(broadcast.reserveClick(9101),"broadcast-only second cycle click");
        TimedClickGate adjustable = new TimedClickGate();
        check(adjustable.getCooldownMs()==100L,"default cooldown is 100ms");
        check(adjustable.setCooldownMs(150),"150ms accepted");
        check(adjustable.getCooldownMs()==150L,"150ms applied");
        check(adjustable.admitTrigger(10000),"adjusted gate trigger");
        check(!adjustable.admitTrigger(10100),"adjusted 150ms gate blocks 100ms");
        check(adjustable.admitTrigger(10171),"adjusted 150ms gate releases after cooldown and debounce");
        check(adjustable.setCooldownMs(200),"200ms accepted while current cycle already started");
        check(adjustable.admitTrigger(10350),"current cycle keeps its 150ms duration");
        check(!adjustable.admitTrigger(10480),"new cycle obeys 200ms duration");
        check(adjustable.admitTrigger(10551),"new cycle unlocks after 200ms");
        check(adjustable.setCooldownMs(79),"below old minimum accepted");
        check(adjustable.setCooldownMs(2001),"above old maximum accepted");
        check(adjustable.setCooldownMs(Integer.MAX_VALUE),"maximum supported int accepted");
        check(!adjustable.setCooldownMs(-1),"negative value rejected");
        check(adjustable.getCooldownMs()==Integer.MAX_VALUE,"invalid input does not change setting");
        check(adjustable.setCooldownMs(0),"zero disables cooldown");
        TimedClickGate zero = new TimedClickGate();
        check(zero.setCooldownMs(0),"zero accepted");
        check(zero.admitTrigger(1000),"zero trigger admitted");
        check(zero.reserveClick(1000),"one click still possible with zero cooldown");
        check(!zero.reserveClick(1001),"no duplicate click within same cycle");
        check(zero.admitTrigger(1100),"next trigger admitted without cooldown");
        check(zero.admitBroadcast(1110),"broadcast of next trigger admitted");
        check(zero.reserveClick(1120),"click of next cycle admitted");
        TimedClickGate one = new TimedClickGate();
        check(one.setCooldownMs(1),"1 ms accepted");
        check(one.admitTrigger(3000),"1 ms trigger accepted");
        check(one.reserveClick(3050),"native click still possible within 100ms at 1ms setting");
        check(!one.reserveClick(3051),"no second click even with 1ms setting");
        check(adjustable.setCooldownMs(1),"1 ms accepted");
        check(adjustable.setCooldownMs(80),"80 ms accepted");
        check(adjustable.setCooldownMs(2000),"2000 ms accepted");
        System.out.println("TimedClickGateTest OK: "+assertions+" assertions");
    }
}
